#!/usr/bin/env python3
"""Sync auto-drive logs to a dedicated GitHub branch.

The uploader uses a temporary Git repository, so the active openpilot worktree
and its uncommitted changes are never touched. Only compressed replayable logs
and a manifest are committed to the logs branch.
"""
from __future__ import annotations

import argparse
import fcntl
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

from openpilot.system.hardware.hw import Paths


DEFAULT_REMOTE = os.getenv("AUTO_LOG_GIT_REMOTE", "git@github.com:liuhb1985/openpilot.git")
DEFAULT_BRANCH = os.getenv("AUTO_LOG_GIT_BRANCH", "cpv9-pc-dst-logs")
DEFAULT_LOG_DIR = Path(os.path.dirname(Paths.log_root())) / "auto_drive"
UPLOAD_STATUS = Path("/tmp/auto_drive_upload_status.json")
LOCK_FILE = Path("/tmp/auto_drive_upload.lock")


def run(cmd: list[str], cwd: Path | None = None, check: bool = True, capture: bool = True) -> subprocess.CompletedProcess:
  result = subprocess.run(cmd, cwd=cwd, text=True, capture_output=capture, timeout=300)
  if check and result.returncode != 0:
    raise RuntimeError(f"command failed: {' '.join(cmd)}\n{result.stdout or ''}{result.stderr or ''}")
  return result


def sha256(path: Path) -> str:
  h = hashlib.sha256()
  with path.open("rb") as f:
    while chunk := f.read(8 * 1024 * 1024):
      h.update(chunk)
  return h.hexdigest()


def snapshot(log_dir: Path) -> dict:
  files = {}
  for path in sorted(log_dir.glob("auto_drive_*.bz2")):
    if not path.is_file():
      continue
    files[path.name] = {
      "size": path.stat().st_size,
      "sha256": sha256(path),
      "mtime": int(path.stat().st_mtime),
    }
  return files


def write_upload_status(data: dict) -> None:
  tmp = UPLOAD_STATUS.with_suffix(".json.tmp")
  with tmp.open("w", encoding="utf-8") as f:
    json.dump(data, f, ensure_ascii=False, indent=2)
  os.replace(tmp, UPLOAD_STATUS)


def sync_once(remote: str, branch: str, log_dir: Path) -> dict:
  files = snapshot(log_dir)
  total_bytes = sum(v["size"] for v in files.values())
  result = {
    "time": int(time.time()),
    "remote": remote,
    "branch": branch,
    "files": len(files),
    "totalBytes": total_bytes,
    "synced": False,
    "reason": "",
    "commit": "",
  }

  if not files:
    result["reason"] = "no logs"
    write_upload_status(result)
    return result

  with tempfile.TemporaryDirectory(prefix="auto_drive_git_") as td:
    repo = Path(td)
    run(["git", "init", "-q", "-b", branch], cwd=repo)
    run(["git", "config", "user.name", "liuhb1985"], cwd=repo)
    run(["git", "config", "user.email", "liuhb1985@163.com"], cwd=repo)
    run(["git", "remote", "add", "origin", remote], cwd=repo)

    fetch = run(["git", "fetch", "-q", "--depth=1", "origin", f"refs/heads/{branch}"], cwd=repo, check=False)
    branch_exists = fetch.returncode == 0

    if branch_exists:
      run(["git", "checkout", "-q", "-B", branch, "FETCH_HEAD"], cwd=repo)
      manifest_path = repo / "manifest.json"
      if manifest_path.exists():
        try:
          old = json.loads(manifest_path.read_text(encoding="utf-8"))
          if old.get("files") == files:
            result["reason"] = "already up to date"
            write_upload_status(result)
            return result
        except Exception:
          pass
    else:
      (repo / "README.md").write_text(
        "# Auto drive logs\n\nGenerated by `tools/logging/upload_auto_drive_logs.py`.\n",
        encoding="utf-8",
      )

    def prepare_commit(message: str) -> bool:
      dest = repo / "logs" / "auto_drive"
      if dest.exists():
        shutil.rmtree(dest)
      dest.mkdir(parents=True, exist_ok=True)
      for name in files:
        shutil.copy2(log_dir / name, dest / name)

      status = Path("/tmp/auto_drive_status.json")
      status_data = {}
      if status.exists():
        try:
          status_data = json.loads(status.read_text(encoding="utf-8"))
        except Exception:
          pass

      manifest = {
        "generatedAt": int(time.time()),
        "branch": branch,
        "remote": remote,
        "logDir": str(log_dir),
        "files": files,
        "status": status_data,
      }
      (repo / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
      (repo / "README.md").write_text(
        "# Auto drive logs\n\n"
        f"Branch: `{branch}`\n\n"
        "Compressed replayable logs generated by the openpilot auto drive recorder.\n"
        "Open `manifest.json` for file sizes, timestamps, hashes and vehicle status.\n",
        encoding="utf-8",
      )

      run(["git", "add", "-A"], cwd=repo)
      diff = run(["git", "diff", "--cached", "--quiet"], cwd=repo, check=False)
      if diff.returncode == 0:
        return False
      run(["git", "commit", "-q", "-m", message], cwd=repo)
      return True

    stamp = time.strftime("%Y-%m-%d %H:%M:%S")
    message = f"logs: auto drive {stamp} ({len(files)} files)"
    if not prepare_commit(message):
      result["reason"] = "no changes"
      write_upload_status(result)
      return result

    push = run(["git", "push", "-q", "origin", f"HEAD:refs/heads/{branch}"], cwd=repo, check=False)
    if push.returncode != 0:
      # Another uploader may have advanced the branch between fetch and push.
      # Rebuild our commit on top of the latest remote state without force push.
      refetch = run(["git", "fetch", "-q", "--depth=1", "origin", f"refs/heads/{branch}"], cwd=repo, check=False)
      if refetch.returncode != 0:
        raise RuntimeError(push.stderr or "push failed")
      run(["git", "reset", "--hard", "-q", "FETCH_HEAD"], cwd=repo)
      reason = "uploaded after refetch"
      if prepare_commit(message):
        push = run(["git", "push", "-q", "origin", f"HEAD:refs/heads/{branch}"], cwd=repo, check=False)
        if push.returncode != 0:
          raise RuntimeError(push.stderr or "push failed after refetch")
      else:
        reason = "already up to date after refetch"

    head = "HEAD" if push.returncode == 0 else "FETCH_HEAD"
    commit = run(["git", "rev-parse", head], cwd=repo).stdout.strip()
    result.update({"synced": True, "reason": result.get("reason") or "uploaded", "commit": commit})
    if result["reason"] == "uploaded":
      result["reason"] = reason if push.returncode == 0 and result.get("reason") == "uploaded" else result["reason"]
    write_upload_status(result)
    print(f"[auto_upload] uploaded {len(files)} files ({total_bytes / 1024 / 1024:.1f} MB) -> {branch}", flush=True)
    return result


def main() -> None:
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--once", action="store_true", help="sync once and exit")
  parser.add_argument("--loop", action="store_true", help="run forever")
  parser.add_argument("--interval", type=float, default=float(os.getenv("AUTO_LOG_UPLOAD_INTERVAL", "600")))
  parser.add_argument("--remote", default=DEFAULT_REMOTE)
  parser.add_argument("--branch", default=DEFAULT_BRANCH)
  parser.add_argument("--log-dir", default=str(DEFAULT_LOG_DIR))
  args = parser.parse_args()

  log_dir = Path(args.log_dir).expanduser().resolve()

  while True:
    try:
      with LOCK_FILE.open("w") as lock:
        try:
          fcntl.flock(lock.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
          write_upload_status({
            "time": int(time.time()),
            "remote": args.remote,
            "branch": args.branch,
            "synced": False,
            "reason": "another uploader is running",
          })
          print("[auto_upload] another uploader is running, skip", flush=True)
        else:
          sync_once(args.remote, args.branch, log_dir)
    except Exception as e:
      result = {
        "time": int(time.time()),
        "remote": args.remote,
        "branch": args.branch,
        "synced": False,
        "reason": f"error: {e!r}",
      }
      write_upload_status(result)
      print(f"[auto_upload] error: {e!r}", flush=True)

    if args.once or not args.loop:
      break
    time.sleep(max(30.0, args.interval))


if __name__ == "__main__":
  main()
